// Alle Polygone gleich orientieren, damit sich überlappende Meere beim Füllen vereinigen
function orient(list) {
  for (const w of list) {
    let a = 0;
    for (let i = 0; i < w.pts.length; i++) {
      const [x0, y0] = w.pts[i], [x1, y1] = w.pts[(i + 1) % w.pts.length];
      a += x0 * y1 - x1 * y0;
    }
    if (a < 0) w.pts.reverse();
  }
}
orient(WATER);
orient(ISLANDS);
