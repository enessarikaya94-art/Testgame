export const MAP_BOUNDS = { lon0: 20, lon1: 94, lat0: 12, lat1: 56 };

// Pixel pro Grad (Weltkoordinaten). Längengrade werden mit cos(36°) gestaucht.
export const PX_PER_DEG = 40;
export const LON_SCALE = Math.cos((36 * Math.PI) / 180);

export const WORLD_W = Math.round((MAP_BOUNDS.lon1 - MAP_BOUNDS.lon0) * PX_PER_DEG * LON_SCALE);
export const WORLD_H = Math.round((MAP_BOUNDS.lat1 - MAP_BOUNDS.lat0) * PX_PER_DEG);

export function project(lon, lat) {
  return [
    (lon - MAP_BOUNDS.lon0) * PX_PER_DEG * LON_SCALE,
    (MAP_BOUNDS.lat1 - lat) * PX_PER_DEG,
  ];
}

