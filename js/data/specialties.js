export function specialtiesOf(pid) {
  return (PROVINCE_SPECIALTIES[pid] || []).map((id) => ({ id, ...SPECIALTIES[id] }));
}

// Summierte Effekte einer Provinz (Zahlenwerte addiert, Listen vereinigt)
const cache = {};
export function specialtyEff(pid) {
  if (cache[pid]) return cache[pid];
  const out = { units: [], resources: [], xp: {} };
  for (const id of PROVINCE_SPECIALTIES[pid] || []) {
    const e = SPECIALTIES[id].eff;
    for (const [k, v] of Object.entries(e)) {
      if (k === 'units') out.units.push(...v);
      else if (k === 'resource') out.resources.push(v);
      else if (k === 'xp') for (const [c, n] of Object.entries(v)) out.xp[c] = (out.xp[c] || 0) + n;
      else out[k] = (out[k] || 0) + v;
    }
  }
  cache[pid] = out;
  return out;
}
