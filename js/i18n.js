// Sprachumschaltung Deutsch / Türkisch

let current = null;
try { current = localStorage.getItem('turan_lang'); } catch (e) { current = null; }
if (current !== 'de' && current !== 'tr') current = (navigator.language || 'de').toLowerCase().startsWith('tr') ? 'tr' : 'de';

const listeners = [];
export function lang() { return current; }
export function setLang(l) {
  current = l === 'tr' ? 'tr' : 'de';
  try { localStorage.setItem('turan_lang', current); } catch (e) { /* ignorieren */ }
  document.documentElement.lang = current;
  listeners.forEach((fn) => fn(current));
}
export function onLangChange(fn) { listeners.push(fn); }

export function L(v) {
  if (v === null || v === undefined) return '';
  if (typeof v === 'string' || typeof v === 'number') return String(v);
  return v[current] ?? v.de ?? '';
}

export function t(key, params = {}) {
  let s = STR[current][key] ?? STR.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    const v = params[k];
    if (v === undefined || v === null) return '';
    if (typeof v === 'number') return String(Math.round(v * 10) / 10);
    return L(v);
  });
}

